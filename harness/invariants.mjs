/**
 * Phase 7 invariant sweep — partial baseline.
 *
 * The spec is explicit that only the FULL phase-7 numbers count: measuring nine
 * invariants at nine different points in a moving codebase and calling it nine
 * passes is not a pass. This run is therefore deliberately split:
 *
 *   GROUP A — measurable today. Real results. I7 is a PHASE 0 acceptance test
 *     (the engines were unified in phase 0), so a failure there is a bug to fix
 *     now, not a future-phase gap. I1/I3/I4 are recorded as the pre-economy
 *     BASELINE that phases 2-4 get judged against.
 *
 *   GROUP B — not measurable. Listed with the specific missing system and NOT
 *     run, so the reason each is absent is on the record rather than implied.
 *
 * Everything here calls the real shipped code. Nothing is re-implemented: an
 * earlier version of this project's economy modelling was a standalone
 * Math.random() script that never touched the server, and it was reported as a
 * measurement. It was not one.
 *
 * Usage: node harness/invariants.mjs
 */
import { spawnSync } from "node:child_process";
import path from "node:path";
import fs from "node:fs";

const REPO = path.join(import.meta.dirname, "..");
const ELECTRON = path.join(REPO, "node_modules", "electron", "dist", "electron.exe");
const TSX = path.join(REPO, "node_modules", ".pnpm", "tsx@4.21.0",
  "node_modules", "tsx", "dist", "cli.mjs");

const NEWLINE = String.fromCharCode(10);
const bar = (c) => c.repeat(74);

let failures = 0;
const results = [];

function record(id, name, verdict, detail) {
  results.push({ id, name, verdict, detail });
  if (verdict === "FAIL") failures++;
  const tag = verdict === "PASS" ? "PASS" : verdict === "FAIL" ? "FAIL" : verdict;
  console.log(`  ${tag.padEnd(9)} ${id} ${name}`);
  for (const line of String(detail).split(NEWLINE)) console.log(`            ${line}`);
}

/**
 * Run a probe inside the api-server package, under Electron's node so the
 * native better-sqlite3 ABI matches, importing the REAL engine modules.
 */
function probe(source) {
  const file = path.join(REPO, "artifacts", "api-server", "src", `__probe_${Date.now()}.ts`);
  fs.writeFileSync(file, source);
  try {
    const r = spawnSync(ELECTRON, [TSX, file], {
      cwd: path.join(REPO, "artifacts", "api-server"),
      encoding: "utf8",
      env: { ...process.env, ELECTRON_RUN_AS_NODE: "1", DB_PATH: path.join(REPO, "lib", "db", "volleyball-empire.sqlite") },
    });
    if (r.status !== 0) {
      throw new Error(`probe failed (${r.status}):${NEWLINE}${r.stdout}${NEWLINE}${r.stderr}`);
    }
    const line = r.stdout.trim().split(NEWLINE).filter((l) => l.startsWith("{")).pop();
    if (!line) throw new Error(`probe produced no JSON:${NEWLINE}${r.stdout}${NEWLINE}${r.stderr}`);
    return JSON.parse(line);
  } finally {
    fs.rmSync(file, { force: true });
  }
}

